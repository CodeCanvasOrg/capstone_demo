// Vercel traces a function's dependencies statically (@vercel/nft), but AdonisJS loads
// config files, jobs, listeners, etc. by scanning directories at runtime. This writes
// build/vercel_manifest.js with a never-called import() of every compiled server file so
// the tracer bundles them and the npm packages they use, and nothing else.
import { readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const buildDir = path.resolve(process.argv[2] ?? 'build')
// Not needed at runtime: tests, ace commands, DB seeders/factories, the Vite config.
const SKIP_DIRS = new Set(['node_modules', 'public', 'tests', 'commands', 'seeders', 'factories'])
const SKIP_FILES = new Set(['vite.config.js', 'ace.js', 'vercel_manifest.js'])

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(full, out)
    } else if (entry.name.endsWith('.js') && !SKIP_FILES.has(entry.name)) {
      out.push(full)
    }
  }
  return out
}

const files = walk(buildDir)
  .map((file) => './' + path.relative(buildDir, file).split(path.sep).join('/'))
  .sort()

writeFileSync(
  path.join(buildDir, 'vercel_manifest.js'),
  `// Generated by scripts/vercel_manifest.mjs. Never executed; read by Vercel's file tracer.\n` +
    `export const trace = () => [\n${files.map((f) => `  import(${JSON.stringify(f)}),`).join('\n')}\n]\n`
)
console.log(`vercel_manifest.js: ${files.length} files`)
