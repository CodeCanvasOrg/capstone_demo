// Generates shared/canvas/portfolio/inter_metrics.ts: the advance width of every character the
// portfolio template can print, in each of its four font files, measured in Chromium.
// Run from the repository root: node scripts/portfolio_metrics.mjs
import { readFile, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'

const FONTS = [
  ['400', 'Inter', 400, 'Inter-400-14.ttf'],
  ['600', 'Inter', 600, 'Inter-600-14.ttf'],
  ['700', 'Inter', 700, 'Inter-700-14.ttf'],
  ['display', 'Inter Display', 700, 'Inter-700-32.ttf'],
]
const codes = []
for (let c = 0x20; c <= 0x7e; c++) codes.push(c)
for (let c = 0xa0; c <= 0xff; c++) codes.push(c)
codes.push(0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026, 0x2022, 0x2212, 0x2192, 0x20ac, 0x2264, 0x2265)

const faces = await Promise.all(
  FONTS.map(async ([, family, weight, file]) => {
    const data = (await readFile(new URL(`../resources/fonts/portfolio/${file}`, import.meta.url))).toString('base64')
    return `@font-face{font-family:"${family}";font-weight:${weight};src:url(data:font/ttf;base64,${data})}`
  })
)
const browser = await chromium.launch()
const page = await browser.newPage()
await page.setContent(`<style>${faces.join('')}</style><p style="font-family:Inter">x</p>`)
const widths = await page.evaluate(async ({ fonts, codes }) => {
  const out = {}
  for (const [key, family, weight] of fonts) {
    await document.fonts.load(`${weight} 1000px "${family}"`)
    const ctx = document.createElement('canvas').getContext('2d')
    ctx.font = `${weight} 1000px "${family}"`
    out[key] = codes.map((c) => Math.round(ctx.measureText(String.fromCodePoint(c)).width * 10) / 10)
  }
  return out
}, { fonts: FONTS, codes })
await browser.close()

const lines = [
  '// Generated by scripts/portfolio_metrics.mjs from resources/fonts/portfolio/*.ttf. Do not edit.',
  '// Advance widths in thousandths of an em, by code point.',
  `export const METRIC_CODES: readonly number[] = ${JSON.stringify(codes)}`,
  'export const METRIC_WIDTHS: Record<"400" | "600" | "700" | "display", readonly number[]> = {',
  ...Object.entries(widths).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
  '}',
  '',
]
await writeFile(new URL('../shared/canvas/portfolio/inter_metrics.ts', import.meta.url), lines.join('\n'))
console.log('wrote', codes.length, 'characters')
