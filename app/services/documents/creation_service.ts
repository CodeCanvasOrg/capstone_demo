import { randomUUID } from 'node:crypto'
import db from '@adonisjs/lucid/services/db'
import type { TransactionClientContract } from '@adonisjs/lucid/types/database'
import DocumentService, { type DocumentInput } from '#services/documents/document_service'
import GenerationService from '#services/documents/generation_service'
import env from '#start/env'
import OutlineTemplateService from '#services/documents/outline_template_service'
import DocumentLayout from '#models/document_layout'
import { DEFAULT_TEMPLATE_ID } from '../../../shared/layout/templates.ts'
import { pinLayout } from '#services/layout/layout_validation'
import { BRANDED_TEMPLATE_ID, BROCHURE_TEMPLATE_ID } from '../../../shared/templates/outlines.ts'
import { resolveInstructions } from '../../../shared/templates/instructions.ts'
import { type WorkspaceAccessContext } from '#services/workspaces/access_service'
import { canvasGenerationEnabled } from '#services/canvas/generation/canvas_generation_service'
import { Exception } from '@adonisjs/core/exceptions'
import { canvasOptionsSchema, type CanvasOptions } from '../../../shared/canvas/options.ts'
export const PENDING_TITLE = 'Untitled case study'
/** New documents use the branded entry unless the deployment opts back to the old outline. */
const legacyFormat = () => env.get('GENERATION_FORMAT') === 'legacy'
const defaultTemplateId = () => (legacyFormat() ? 'portfolio' : BRANDED_TEMPLATE_ID)
/**
 * The canvas options a new case study is created with, or null for the brochure behaviour.
 * The portfolio fields are validated by the shared schema. `templateSet` is read apart from it
 * and passed through, so a set the schema does not know yet ("Let AI choose") is kept as sent
 * instead of being coerced or rejected here.
 */
export function creationCanvas(input: { templateId?: string | null; canvas?: unknown }) {
  if (input.templateId !== BROCHURE_TEMPLATE_ID || input.canvas === undefined) return null
  if (!canvasGenerationEnabled()) return null
  const raw =
    input.canvas && typeof input.canvas === 'object' && !Array.isArray(input.canvas)
      ? (input.canvas as Record<string, unknown>)
      : {}
  const { templateSet, ...rest } = raw
  const parsed = canvasOptionsSchema.safeParse(rest)
  if (!parsed.success || (templateSet !== undefined && typeof templateSet !== 'string'))
    throw new Exception('Choose a depth, an entry count and images setting the portfolio offers.', {
      status: 422,
      code: 'E_CANVAS_OPTIONS',
    })
  const known = canvasOptionsSchema.safeParse({ ...rest, templateSet })
  return {
    ...parsed.data,
    // What the schema keeps of the set (the portfolio) unless it rejects the value as unknown.
    templateSet: known.success ? known.data.templateSet : (templateSet as string),
  } as CanvasOptions
}

export default class CreationService {
  async document(
    context: WorkspaceAccessContext,
    allInput: Omit<DocumentInput, 'title'> & {
      title?: string
      templateId?: string | null
      instructions?: string | null
      /** The brochure's page designs. With no selection the model chooses every page. */
      brochure?: unknown
      /**
       * Canvas options from "Use a template" or "Let AI choose". With canvas generation on the
       * case study is created in canvas mode and generated by the canvas pipeline; otherwise
       * the brochure above is used.
       */
      canvas?: unknown
    },
    fileIds: string[],
    client?: TransactionClientContract
  ) {
    const { instructions, brochure, canvas: canvasInput, ...input } = allInput
    const canvas = creationCanvas({ templateId: input.templateId, canvas: canvasInput })
    const create = async (trx: TransactionClientContract) => {
      const outline =
        input.templateId === null
          ? null
          : await new OutlineTemplateService().resolve(input.templateId ?? defaultTemplateId(), {
              legacy: legacyFormat(),
            })
      const generateTitle = !input.title
      const doc = await new DocumentService().create(
        context,
        { ...input, title: input.title || PENDING_TITLE },
        fileIds,
        trx
      )
      doc.merge({
        selectedTemplateVersionId: null,
        templateSetup: {
          ...(outline ? { outline } : {}),
          ...(generateTitle ? { generateTitle } : {}),
          instructions: resolveInstructions(instructions),
        },
      })
      await doc.save()
      if (canvas) {
        // Canvas mode from the start: the options are stored as sent (no brochure pages), and the
        // generation below runs the canvas pipeline with them.
        const pinned = pinLayout({ templateId: DEFAULT_TEMPLATE_ID })
        await DocumentLayout.create(
          {
            documentId: doc.id,
            workspaceId: context.workspaceId,
            templateId: pinned.templateId,
            templateVersion: pinned.templateVersion,
            brandId: pinned.brandId,
            brandVersion: pinned.brandVersion,
            options: { ...pinned.options, canvas },
            presetId: null,
            updatedBy: context.actorId,
            revision: 1,
            editorMode: 'canvas',
          },
          { client: trx }
        )
      } else if (input.templateId === BROCHURE_TEMPLATE_ID) {
        // Pinned in this transaction, so the generation requested below writes these pages.
        const pinned = pinLayout({
          templateId: DEFAULT_TEMPLATE_ID,
          options: { brochure: brochure ?? { source: 'ai', pages: ['auto'] } },
        })
        await DocumentLayout.create(
          {
            documentId: doc.id,
            workspaceId: context.workspaceId,
            templateId: pinned.templateId,
            templateVersion: pinned.templateVersion,
            brandId: pinned.brandId,
            brandVersion: pinned.brandVersion,
            options: pinned.options,
            presetId: null,
            updatedBy: context.actorId,
            revision: 1,
          },
          { client: trx }
        )
      }
      await new GenerationService().request(
        context,
        doc.id,
        randomUUID(),
        null,
        trx,
        canvas ?? undefined
      )
      return doc
    }
    return client ? create(client) : db.transaction(create)
  }
}
